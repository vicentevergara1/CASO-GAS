/**
 * Iconos de línea livianos, dibujados en SVG para no agregar dependencias.
 * Son decorativos por defecto; usa `title` solo si el icono comunica por sí solo.
 */
export default function Icon({ name, size = 18, className = "", title }) {
  const content = ICONS[name];
  if (!content) return null;
  return (
    <svg
      className={`icon ${className}`.trim()}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.9"
      strokeLinecap="round"
      strokeLinejoin="round"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : "true"}
      focusable="false"
    >
      {title ? <title>{title}</title> : null}
      {content}
    </svg>
  );
}
